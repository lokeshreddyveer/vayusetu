#!/usr/bin/env python3
"""Writes ios/BUILD-STATUS.md from the version files and the recorded test evidence; nothing in it is typed by hand.

  python3 ios/scripts/build-status.py            # rewrite the file
  python3 ios/scripts/build-status.py --check    # exit 1 when the file on disk differs from what the files would produce

It holds no commit hash, so committing the result does not make it stale. "Not recorded" means no run has left evidence, which is different from passing."""
import json, sys
from pathlib import Path

repo = Path(__file__).resolve().parents[2]
def load(path):
    try: return json.loads((repo / path).read_text())
    except (OSError, ValueError): return None

ios, mac = load("ios/Configuration/Version.json"), load("macos/scripts/version.json")
ui, sec = load("ios/test-evidence/ui-run.json"), load("macos/test-evidence/security-run.json")
lines = ["# Build status", "", "Generated by `ios/scripts/build-status.py` from the version files and recorded test runs. Do not edit by hand; `macos/tools/verify-release.sh` fails when it is out of date.", "",
         "## Versions", "", "| | Marketing | Build | Notes |", "|---|---|---|---|"]
if ios: lines.append(f"| iPhone | {ios['marketing']} | {ios['build']} | `ios/Configuration/Version.json` |")
if mac: lines.append(f"| Mac app | {mac['marketing']} | {mac['build']} | tunnel extension {mac['tunnel']}, network filter {mac['filter']} (`macos/scripts/version.json`) |")
lines += ["", "## Recorded runs", ""]
gaps = []
if ui:
    skipped = ui.get("skipped") or []
    lines.append(f"- iPhone UI tests: {len(ui.get('passed', []))} passed" + (f", {len(skipped)} did not run" if skipped else "") + f" on {ui.get('device')} ({ui.get('os')}), recorded {ui.get('recorded')}.")
else:
    lines.append("- iPhone UI tests: not recorded."); gaps.append("The iPhone UI test suite has not been run on a device (`ios/scripts/test-ui.sh`, then `ios/scripts/ui-evidence.py record`).")
if sec:
    state = "no failures" if not sec["failed"] else f"{sec['failed']} FAILED"
    lines.append(f"- Mac runtime security checks (`macos/tools/verify-security.sh`): {sec['passed']} passed, {sec['notVerified']} not verified, {state}; build {sec['build']}, recorded {sec['recorded']}" + ("" if sec.get("withVPN") else " (DNS-only mode)") + ".")
    if mac and sec["build"] != mac["build"]: gaps.append(f"The recorded security run was for build {sec['build']}; the current build is {mac['build']}.")
    if sec["failed"] or sec["notVerified"]: gaps.append("The recorded security run has failed or unverified checks; see its output.")
else:
    lines.append("- Mac runtime security checks: not recorded."); gaps.append("VPN, DNS and filter behaviour has not been observed on a running Mac (`macos/tools/verify-security.sh`).")
lines += ["", "## Not yet shown", ""]
lines += [f"- {g}" for g in gaps] or ["- Nothing outstanding in the recorded evidence."]
lines += ["- Kill switch, recovery after Wi-Fi loss or sleep, and the network filter on live connections cannot be observed by the scripts; they need to be checked by hand.", ""]
text = "\n".join(lines)
target = repo / "ios/BUILD-STATUS.md"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != text: print("ios/BUILD-STATUS.md is out of date; run: python3 ios/scripts/build-status.py"); sys.exit(1)
    print("ios/BUILD-STATUS.md is current"); sys.exit(0)
target.write_text(text); print("wrote", target.relative_to(repo))
